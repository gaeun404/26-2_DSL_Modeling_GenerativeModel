def _shot(text):
    s = text.strip()
    parts = re.split(r"(?<=[.?!—])\s+", s)
    return " ".join(parts[:2])[:130]


def enrich(path, check=False):
    s = json.load(open(path, encoding="utf-8"))
    fname = path.split("/")[-1]
    era = s["background"]["setting_raw"].get("era", "")
    notes = SPECIES_NOTES.get(fname, {})
    tagged = 0
    for b in s["intro"]["narration"]:
        note = notes.get(b["beat"])
        if note:
            tagged += 1
        if check:
            continue
        b["render"] = {
            "shot": _shot(b.get("text", "")),
            "scene": b.get("scene", ""),
            "style": f"{era} 배경의 추리 게임 삽화, 수채화 느낌의 스토리북 일러스트, 극적인 명암",
            "spoiler_ban": "범인을 특정하는 얼굴·이름·복식은 그리지 않는다",
        }
        if note:
            b["render"]["species_note"] = note
    if not check:
        json.dump(s, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    mark = f" · 종(種) 명시 {tagged}비트" if tagged else ""
    print(f"  {fname:28s} 나레이션 {len(s['intro']['narration'])}비트{mark}")
    return tagged


if __name__ == "__main__":
    check = "--check" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    files = args or sorted(glob.glob("scenarios/[0-9]*.json"))
    tot = 0
    for f in files:
        tot += enrich(f, check)
    print(f"\n전체 {len(files)}편 · species_note 부여 {tot}비트")
